#!/usr/bin/env python3
"""Generate the UI theme stylesheet from a theme file.

    scripts/theme/generate_css.py ember              # a name in themes/
    scripts/theme/generate_css.py path/to/theme.json # or a path
    scripts/theme/generate_css.py --list

Writes the theme's tokens as CSS variables to
src/main/resources/static/css/theme.css, only when the text changes. Exits 1
on a theme that fails validation in themes.py.
"""

import argparse
import json
import sys
from pathlib import Path

from themes import (
    FOCUS_RING, HOVER, MODE_GROUPS, ROOT, SHARED_GROUPS, SOFT, InvalidTheme, available_themes,
    display, load_theme, resolve, status, write_text,
)

OUTPUT = ROOT / "src/main/resources/static/css/theme.css"

EXIT_OK = 0
EXIT_INVALID = 1


# --- CSS ---------------------------------------------------------------------


def declarations(values: dict[str, str], groups: list, indent: str) -> list[str]:
    lines = []
    for title, tokens in groups:
        lines.append(f"{indent}/* {title} */")
        lines.extend(f"{indent}--{token}: {values[token]};" for token in tokens)
        lines.append("")
    return lines[:-1]


def root_block(scheme: str, values: dict[str, str], groups: list, indent: str = "    ") -> list[str]:
    body = [f"{indent}color-scheme: {scheme};", "", *declarations(values, groups, indent)]
    return [":root {", *body, "}"]


def mix_rule(name: str, token: str, amount: float, base: str) -> str:
    return f"    --{name}: color-mix(in oklch, var(--{token}) {amount:.0%}, {base});"


def derived_block() -> list[str]:
    """Tints, hovers, and the focus ring, from the amounts the contrast check uses."""
    rules = []
    for token, amount in SOFT.items():
        rules.append(mix_rule(f"{token}-soft", token, amount, "var(--surface)"))
        if token in HOVER:
            rules.append(mix_rule(f"{token}-hover", token, HOVER[token], "var(--text)"))
    focus = f"color-mix(in oklch, var(--primary) {FOCUS_RING:.0%}, transparent)"
    rules.append(f"    --focus-ring: 0 0 0 3px {focus};")
    return ["/* Derived tokens: computed from the roles above. */", ":root {", *rules, "}"]


def render_css(theme: dict, source: str) -> str:
    light = root_block("light", theme["light"] | theme["shared"], MODE_GROUPS + SHARED_GROUPS)
    dark = root_block("dark", theme["dark"], MODE_GROUPS)
    lines = [
        "/*",
        f" * Generated by scripts/theme/generate_css.py from {source}. Do not edit by hand:",
        " * change the theme file and run make theme.",
        f" * Theme: {theme.get('name', source)}. {theme.get('description', '')}".rstrip(),
        " */",
        "",
        *light,
        "",
        "@media (prefers-color-scheme: dark) {",
        *("    " + line if line else line for line in dark),
        "}",
        "",
        *derived_block(),
        "",
    ]
    return "\n".join(lines)


# --- Command line ------------------------------------------------------------


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("theme", nargs="?", help="theme name in themes/ or a JSON path")
    parser.add_argument("--list", action="store_true", help="list the themes in themes/")
    parser.add_argument("--output", type=Path, default=OUTPUT, help="stylesheet to write")
    args = parser.parse_args(argv)
    if not args.list and not args.theme:
        parser.error("a theme or --list is required")
    return args


def list_themes() -> int:
    for path in available_themes():
        theme = json.loads(path.read_text())
        print(f"{path.stem:<10} {theme.get('description', '')}")
    return EXIT_OK


def write_css(theme_arg: str, output: Path) -> int:
    path = resolve(theme_arg)
    css = render_css(load_theme(path), display(path))
    print(f"{status(write_text(output, css))} {display(output)}")
    return EXIT_OK


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    if args.list:
        return list_themes()
    try:
        return write_css(args.theme, args.output)
    except InvalidTheme as error:
        print(error, file=sys.stderr)
        return EXIT_INVALID


if __name__ == "__main__":
    sys.exit(main())
